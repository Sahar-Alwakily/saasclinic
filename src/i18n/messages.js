export const MESSAGES = { ar, he, en, ru };

export function interpolate(str, vars = {}) {
  return String(str || '').replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k])));
}

export function lookup(lang, path) {
  const dict = MESSAGES[lang] || MESSAGES.ar;
  return path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), dict);
}
